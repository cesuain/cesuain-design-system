import { cssVarName, isSemanticColor, tailwindColorName, textStyleName } from "../naming.ts";
import type { ResolvedToken, TokenSet, Typography } from "../types.ts";
import { resolvedCss } from "../values.ts";

type Tree = { [key: string]: Tree | string | Record<string, string | number> };

function insert(tree: Tree, path: string[], value: Tree[string]) {
  let node = tree;
  for (const segment of path.slice(0, -1)) {
    node[segment] ??= {};
    node = node[segment] as Tree;
  }
  node[path.at(-1) as string] = value;
}

function cssValue(t: ResolvedToken): Tree[string] {
  if (t.type === "typography") {
    const v = t.resolved as Typography;
    return {
      fontFamily: resolvedCss({ type: "fontFamily", extensions: t.extensions }, v.fontFamily),
      fontSize: resolvedCss({ type: "dimension", extensions: {} }, v.fontSize),
      fontWeight: v.fontWeight,
      lineHeight: v.lineHeight,
      letterSpacing: resolvedCss({ type: "dimension", extensions: {} }, v.letterSpacing),
      textTransform: t.extensions.textTransform ?? "none",
    };
  }
  return resolvedCss(t, t.resolved);
}

function varValue(t: ResolvedToken): Tree[string] {
  const name = cssVarName(t);
  if (t.type === "typography") {
    return {
      fontFamily: `var(${name}-font-family)`,
      fontSize: `var(${name}-font-size)`,
      fontWeight: `var(${name}-font-weight)`,
      lineHeight: `var(${name}-line-height)`,
      letterSpacing: `var(${name}-letter-spacing)`,
    };
  }
  return `var(${name})`;
}

/** Renders a value tree as a readonly TypeScript type literal. */
function typeOf(value: Tree[string], indent = ""): string {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number") return String(value);
  const inner = `${indent}  `;
  const entries = Object.entries(value).map(
    ([k, v]) =>
      `${inner}readonly ${/^[a-zA-Z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${typeOf(v, inner)};`,
  );
  return `{\n${entries.join("\n")}\n${indent}}`;
}

export function jsModules(set: TokenSet): { js: string; dts: string } {
  const byTheme: Tree = {};
  for (const theme of set.themes) {
    const tree: Tree = {};
    for (const t of [...set.base, ...(set.themed[theme] ?? [])]) insert(tree, t.path, cssValue(t));
    byTheme[theme] = tree;
  }
  const vars: Tree = {};
  for (const t of [...set.base, ...(set.themed[set.defaultTheme] ?? [])])
    insert(vars, t.path, varValue(t));

  const all = [...set.base, ...(set.themed[set.defaultTheme] ?? [])];
  const tailwind = {
    colors: (set.themed[set.defaultTheme] ?? []).filter(isSemanticColor).map(tailwindColorName),
    text: set.base.filter((t) => t.type === "typography").map(textStyleName),
    radius: all
      .filter(
        (t) =>
          t.path[0] === "radius" &&
          t.path.length === 2 &&
          t.path[1] !== "none" &&
          t.path[1] !== "full",
      )
      .map((t) => t.path[1] as string),
    shadow: all.flatMap((t) =>
      t.type !== "shadow"
        ? []
        : t.path[0] === "elevation"
          ? [`elevation-${t.path[1]}`]
          : t.path[1] === "glow"
            ? [`glow-${t.path[2]}`]
            : [],
    ),
    font: set.base.filter((t) => t.type === "fontFamily").map((t) => t.path.at(-1) as string),
    ease: set.base
      .filter((t) => t.type === "cubicBezier" && t.path[1] !== "linear")
      .map((t) => t.path[1] as string),
  };

  const header =
    "// Generated by @cesuain/tokens — do not edit by hand. Run `pnpm tokens:build`.\n";
  const js = `${header}
/** Theme names, default first. */
export const themes = ${JSON.stringify(set.themes)};

/** Theme applied on :root when no data-theme attribute or class is present. */
export const defaultTheme = ${JSON.stringify(set.defaultTheme)};

/** Fully resolved CSS values per theme. Prefer \`vars\` in components so theming stays dynamic. */
export const tokens = ${JSON.stringify(byTheme, null, 2)};

/** CSS custom property references, e.g. \`vars.color.card.default === "var(--card)"\`. */
export const vars = ${JSON.stringify(vars, null, 2)};

/** Token-derived class name groups, used to configure tailwind-merge. */
export const tailwindTheme = ${JSON.stringify(tailwind, null, 2)};
`;

  const dts = `${header}
export type ThemeName = ${set.themes.map((t) => JSON.stringify(t)).join(" | ")};

export declare const themes: readonly ThemeName[];
export declare const defaultTheme: ${JSON.stringify(set.defaultTheme)};

export interface ThemeTokens ${typeOf(byTheme[set.defaultTheme] as Tree)
    .replace(/: "[^"]*";/g, ": string;")
    .replace(/: -?\d+(\.\d+)?;/g, ": number;")}

export declare const tokens: { readonly [Theme in ThemeName]: ThemeTokens };

export declare const vars: ${typeOf(vars)};

export declare const tailwindTheme: {
  readonly colors: readonly string[];
  readonly text: readonly ${tailwind.text.length ? `(${tailwind.text.map((t) => JSON.stringify(t)).join(" | ")})` : "string"}[];
  readonly radius: readonly string[];
  readonly shadow: readonly string[];
  readonly font: readonly string[];
  readonly ease: readonly string[];
};
`;
  return { js, dts };
}
