import { cssVarName, isSemanticColor, tailwindColorName, textStyleName } from "../naming.ts";
import type { ResolvedToken, TokenSet } from "../types.ts";
import { declarations, dimension, type Lookup } from "../values.ts";

export const HEADER = (what: string) =>
  `/**\n * ${what}\n * Generated by @cesuain/tokens from src/**.json — do not edit by hand.\n * Run \`pnpm tokens:build\` to regenerate.\n */\n`;

function block(selector: string, tokens: ResolvedToken[], lookup: Lookup, extra: string[] = []) {
  const lines = [...extra];
  for (const token of tokens) {
    for (const [name, value] of declarations(token, lookup)) lines.push(`${name}: ${value};`);
  }
  return `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`;
}

function themeSelector(theme: string, isDefault: boolean): string {
  const selectors = [`[data-theme="${theme}"]`, `.${theme}`];
  return (isDefault ? [":root", ...selectors] : selectors).join(",\n");
}

/** Runtime custom properties: theme-independent tokens on :root, then one block per theme. */
export function tokensCss(set: TokenSet): string {
  const baseLookup: Lookup = new Map(set.base.map((t) => [t.name, t]));
  const parts = [
    HEADER("Cesuain Design System — CSS custom properties"),
    block(":root", set.base, baseLookup),
  ];
  for (const theme of set.themes) {
    const themed = set.themed[theme] ?? [];
    const lookup: Lookup = new Map([...set.base, ...themed].map((t) => [t.name, t]));
    parts.push(
      block(themeSelector(theme, theme === set.defaultTheme), themed, lookup, [
        `color-scheme: ${theme === "light" ? "light" : "dark"};`,
      ]),
    );
  }
  return parts.join("\n");
}

/**
 * Tailwind CSS v4 bridge. `@theme inline` maps tokens onto Tailwind's namespaces so
 * utilities such as `bg-card`, `rounded-control`, `text-display-xl` and `shadow-elevation-lg`
 * resolve to the runtime variables above.
 */
export function themeCss(set: TokenSet): string {
  const themed = set.themed[set.defaultTheme] ?? [];
  const all = [...set.base, ...themed];
  const lines: string[] = [];
  const add = (name: string, value: string) => lines.push(`${name}: ${value};`);
  const v = (t: ResolvedToken) => `var(${cssVarName(t)})`;

  lines.push("/* Colors */");
  for (const t of themed.filter(isSemanticColor)) add(`--color-${tailwindColorName(t)}`, v(t));

  lines.push("", "/* Font families */");
  for (const t of set.base.filter((t) => t.type === "fontFamily"))
    add(`--font-${t.path.at(-1)}`, v(t));

  lines.push("", "/* Text styles: text-<name> sets size, line height, tracking and weight */");
  for (const t of set.base.filter((t) => t.type === "typography")) {
    const n = textStyleName(t);
    const base = cssVarName(t);
    add(`--text-${n}`, `var(${base}-font-size)`);
    add(`--text-${n}--line-height`, `var(${base}-line-height)`);
    add(`--text-${n}--letter-spacing`, `var(${base}-letter-spacing)`);
    add(`--text-${n}--font-weight`, `var(${base}-font-weight)`);
  }

  lines.push("", "/* Radii */");
  for (const t of all.filter((t) => t.path[0] === "radius" && t.path.length === 2)) {
    const n = t.path[1];
    if (n === "none" || n === "full") continue;
    add(`--radius-${n}`, v(t));
  }

  lines.push("", "/* Shadows */");
  for (const t of all.filter((t) => t.type === "shadow")) {
    if (t.path[0] === "elevation") add(`--shadow-elevation-${t.path[1]}`, v(t));
    if (t.path[0] === "shadow" && t.path[1] === "glow") add(`--shadow-glow-${t.path[2]}`, v(t));
  }

  lines.push("", "/* Easing */");
  for (const t of set.base.filter((t) => t.type === "cubicBezier")) {
    if (t.path[1] === "linear") continue;
    add(`--ease-${t.path[1]}`, v(t));
  }

  lines.push("", "/* Containers: max-w-<name> */");
  for (const t of set.base.filter((t) => t.path[0] === "size" && t.path[1] === "content")) {
    add(`--container-${t.path[2]}`, v(t));
  }
  for (const t of set.base.filter((t) => t.path[0] === "size" && t.path[1] === "container")) {
    add(`--container-page-${t.path[2]}`, v(t));
  }

  lines.push("", "/* Breakpoints must be static values to work inside media queries */");
  for (const t of set.base.filter((t) => t.path[0] === "breakpoint")) {
    add(`--breakpoint-${t.path[1]}`, dimension(t.resolved as { value: number; unit: "rem" }));
  }

  return `${HEADER("Cesuain Design System — Tailwind CSS v4 theme bridge")}\n@theme inline {\n${lines
    .map((l) => (l ? `  ${l}` : ""))
    .join("\n")}\n}\n`;
}
